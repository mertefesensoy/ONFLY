def gen_python():
    head_fmt = ">" + "".join(py_code_of(f) for f in M.HEAD)
    out_fmt = ">" + "".join(py_code_of(f) for f in M.OUT)
    L = ["# -*- coding: utf-8 -*-"]
    L += ["# " + b for b in BANNER]
    L.append("")
    L.append("import struct")
    L.append("")
    L.append("RECORD_LEN = %d" % M.RECORD_LEN)
    L.append("HEAD_LEN   = %d" % M.HEAD_LEN)
    L.append("MAX_OUT    = %d" % M.MAX_OUT)
    L.append("OUT_LEN    = %d" % M.OUT_ENTRY_LEN)
    L.append("")
    L.append("# Big-endian struct formats (IR-COM-04).")
    L.append("HEAD_FMT = %r" % head_fmt)
    L.append("OUT_FMT  = %r" % out_fmt)
    L.append("HEAD_FIELDS = %r" % [f.name for f in M.HEAD])
    L.append("OUT_FIELDS  = %r" % [f.name for f in M.OUT])
    L.append("")
    L.append("assert struct.calcsize(HEAD_FMT) == HEAD_LEN")
    L.append("assert struct.calcsize(OUT_FMT) == OUT_LEN")
    L.append("assert HEAD_LEN + MAX_OUT * OUT_LEN == RECORD_LEN")
    L.append("")
    L.append("# Absolute offsets of the fixed part.")
    L.append("OFF = {")
    for f in M.HEAD:
        L.append("    %r: %d," % (f.name, f.off))
    L.append("}")
    L.append("")
    L.append("# Offsets inside one ONF-OUT entry.")
    L.append("OUT_OFF = {")
    for f in M.OUT:
        L.append("    %r: %d," % (f.name, f.off))
    L.append("}")
    L.append("")
    L.append("# Declared value ranges (IR-COM-02).")
    L.append("RANGES = {")
    for f in M.HEAD + M.OUT:
        if f.lo is not None:
            L.append("    %r: (%d, %d)," % (f.name, f.lo, f.hi))
    L.append("}")
    L.append("")
    L.append("# --- Network file header (IR-NET-01, SRS section 4.1) ---------------")
    L.append("NETHDR_LEN        = %d" % M.NETHDR_LEN)
    L.append("NETHDR_CRC_COVERS = %d" % M.NETHDR_CRC_COVERS)
    L.append("NET_ALIGN         = %d" % M.NET_ALIGN)
    L.append("NET_MAGIC         = 0x%08X" % M.NET_MAGIC)
    L.append("NET_SENTINEL      = 0x%08X" % M.NET_SENTINEL)
    L.append("NET_VMAJOR        = %d" % M.NET_VMAJOR)
    L.append("NET_VMINOR        = %d" % M.NET_VMINOR)
    L.append("")
    L.append("# name -> (kind, offset, size); kind is 'u32', 'u16' or 'f64'.")
    L.append("NETHDR = {")
    for name, kind, off, size in M.NETHDR:
        L.append("    %r: (%r, %d, %d)," % (name, kind, off, size))
    L.append("}")
    L.append("")
    L.append("# Stimulus codes and numeric IDs (FR-BAT-05, IR-COM-05, D-39).")
    L.append("STIM_UNKNOWN = %d" % M.STIM_UNKNOWN)
    L.append("STIM_IDS = {")
    for _code, _sid, _note in M.STIM_CODES:
        L.append("    %r: %d," % (_code, _sid))
    L.append("}")
    L.append("")
    L.append("# Declaration order matters when writing the header.")
    L.append("NETHDR_ORDER = %r" % [f[0] for f in M.NETHDR])
    return "\n".join(L) + "\n"


def gen_net_header():
    """C header for the network file header (IR-NET-01, SRS section 4.1)."""
    L = ["/*"]
    L += [" * " + b for b in BANNER]
    L.append(" */")
    L.append("#ifndef ONFNHD_H")
    L.append("#define ONFNHD_H")
    L.append("")
    L.append('#include "onfplat.h"')
    L.append("")
    L.append("/* Header geometry.  The header CRC at ONF_N_HDRCRC covers bytes")
    L.append("   0 .. ONF_NHDR_CRCLEN-1, i.e. everything before itself")
    L.append("   (IR-NET-07). */")
    L.append("#define ONF_NHDR_LEN     %d" % M.NETHDR_LEN)
    L.append("#define ONF_NHDR_CRCLEN  %d" % M.NETHDR_CRC_COVERS)
    L.append("#define ONF_NET_ALIGN    %d" % M.NET_ALIGN)
    L.append("")
    L.append("/* IR-NET-03: compared as an integer on every platform, never as")
    L.append("   text, so a code-page translation in transport is caught. */")
    L.append("#define ONF_NET_MAGIC    0x%08XUL" % M.NET_MAGIC)
    L.append("/* IR-NET-04: any other decoded value fails with ONF102E. */")
    L.append("#define ONF_NET_SENTINEL 0x%08XUL" % M.NET_SENTINEL)
    L.append("#define ONF_NET_VMAJOR   %d" % M.NET_VMAJOR)
    L.append("#define ONF_NET_VMINOR   %d" % M.NET_VMINOR)
    L.append("")
    L.append("/* Field offsets. */")
    for name, kind, off, size in M.NETHDR:
        L.append("#define ONF_N_%-9s %3d   /* %s, %d bytes */"
                 % (name.upper(), off, kind, size))
    L.append("")
    L.append("typedef char onfnhd_len_assert"
             "[(ONF_N_HDRCRC + 4 == ONF_NHDR_LEN) ? 1 : -1];")
    L.append("typedef char onfnhd_crc_assert"
             "[(ONF_N_HDRCRC == ONF_NHDR_CRCLEN) ? 1 : -1];")
    L.append("")
    L.append("#endif /* ONFNHD_H */")
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------------------
# COBOL driver with the copybook expanded in place (IR-COM-01, D-161).
#
# Gate G4 measured on TK5 (2026-09-12) that the MVT ANS COBOL compiler
# rejects the standalone COPY statement (IKF1041I-E) and accepts only the
# COBOL-68 form `01 name COPY member.`, which Enterprise COBOL and GnuCOBOL
# refuse.  No single spelling of COPY compiles on both, so IR-COM-01's
# fallback applies: cobol/ONFLYDRV.cbl keeps its COPY ONFCOM. as honest
# COBOL, and this expands that one statement into generated/ONFLYDRV.cbl,
# which is the single source every compiler builds (FR-BAT-03).
# ---------------------------------------------------------------------------
TEMPLATE = os.path.join(ROOT, "cobol", "ONFLYDRV.cbl")
COPY_LINE = re.compile(r"^ {7}COPY ONFCOM\.\s*$")
ANY_COPY = re.compile(r"^ {6}[^*].*\bCOPY\b")


def gen_cobol_driver(copybook):
    src = io.open(TEMPLATE, encoding="ascii").read().splitlines()
    hits = [i for i, l in enumerate(src) if COPY_LINE.match(l)]
    if len(hits) != 1:
        raise SystemExit("cobol/ONFLYDRV.cbl must contain exactly one "
                         "'COPY ONFCOM.' line, found %d" % len(hits))
    stray = [n + 1 for n, l in enumerate(src)
             if ANY_COPY.match(l) and not COPY_LINE.match(l)]
    if stray:
        raise SystemExit("cobol/ONFLYDRV.cbl has a COPY the generator does "
                         "not expand at line(s) %s" % stray)
    i = hits[0]
    head = []
    for b in [
        "ONFLY generated file - DO NOT EDIT (IR-COM-01, D-18, D-161).",
        "Generated by layout/generate.py from cobol/ONFLYDRV.cbl (the",
        "template) and layout/master.py (the layout).",
        "The template's COPY ONFCOM. is expanded below because MVT COBOL",
        "accepts only the COBOL-68 form of COPY (Gate G4, VL-57).",
        BANNER[2], BANNER[3],
        "Edit cobol/ONFLYDRV.cbl or layout/master.py and regenerate.",
        BANNER[5],
    ]:
        head.extend(_cobol_comment(b))
    head.append("      *")
    body = copybook.rstrip("\n").splitlines()
    lines = (head + src[:i]
             + ["      *---- COPY ONFCOM. expanded by layout/generate.py ----"]
             + body
             + ["      *---- end of ONFCOM ----------------------------------"]
             + src[i + 1:])
    for n, line in enumerate(lines, 1):
        assert len(line) <= 72, "driver line %d past column 72: %r" % (n, line)
    return "\n".join(lines) + "\n"


def main():
    if not os.path.isdir(OUTDIR):
        os.makedirs(OUTDIR)
    copybook = gen_cobol()
    artifacts = [
        ("ONFCOM.cpy", copybook),
        ("ONFLYDRV.cbl", gen_cobol_driver(copybook)),
        ("onfcom.h", gen_c_header()),
        ("onfcom.c", gen_c_source()),
        ("onfcom_py.py", gen_python()),
        ("onfnhd.h", gen_net_header()),
    ]
    for name, text in artifacts:
        path = os.path.join(OUTDIR, name)
        io.open(path, "w", encoding="utf-8", newline="\n").write(text)
        print("generated %-14s %5d bytes" % (name, len(text.encode("utf-8"))))
    print("master.py sha256 %s" % MASTER_SHA)


if __name__ == "__main__":
    main()
